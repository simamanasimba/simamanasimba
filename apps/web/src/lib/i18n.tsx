export type DictKey = keyof typeof DICT.en;

interface LangContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: DictKey) => string;
}

const LangContext = createContext<LangContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  // Public site (landing, login, register…) defaults to Swahili — that's the fan-facing
  // language. Inside the authenticated dashboard we default to English, since staff running
  // the org are assumed to read English; individual admins can still switch it in Settings.
  const isOrgApp = pathname?.startsWith("/org/") ?? false;
  const storageKey = isOrgApp ? "eip:lang:org" : "eip:lang:public";
  const defaultLang: Lang = isOrgApp ? "en" : "sw";
  const [lang, setLangState] = useState<Lang>(defaultLang);

  useEffect(() => {
    try {
      const saved = localStorage.getItem(storageKey);
      if (saved === "en" || saved === "sw") setLangState(saved);
      else setLangState(defaultLang);
    } catch {
      // ignore
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [storageKey]);

  function setLang(l: Lang) {
    setLangState(l);
    try {
      localStorage.setItem(storageKey, l);
    } catch {
      // ignore
    }
  }

  function t(key: DictKey): string {
    return DICT[lang][key] ?? DICT.en[key];
  }

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export function useLang(): LangContextValue {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used within <LanguageProvider>");
  return ctx;
}
